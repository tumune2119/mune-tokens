import { cssColor, isHex } from "../tokens/color";
import { cssVar, modesOf, type Mode, type ShadowToken, type SystemSettings, type TokenSet } from "../tokens/schema";

export interface CssMeta {
  name: string;
  version: number;
  settings: SystemSettings;
}

export function fontStack(family: string, fallback: string) {
  const quoted = /^[\w-]+$/.test(family) ? family : `"${family.replace(/"/g, "")}"`;
  return [quoted, fallback].filter(Boolean).join(", ");
}

export function shadowCss(s: ShadowToken) {
  return s.layers
    .map((l) => `${l.inset ? "inset " : ""}${l.x}px ${l.y}px ${l.blur}px ${l.spread}px ${cssColor(l.color)}`)
    .join(", ");
}

/** Semantic value as CSS: a var() pointing at the primitive, or the raw colour. */
function semanticValue(ref: string) {
  return isHex(ref) ? cssColor(ref) : `var(${cssVar(ref)})`;
}

function header(meta: CssMeta, file: string) {
  return `/* ${file} — ${meta.name} · version ${meta.version} · generated by MUNE Tokens. Edit tokens in the app, not here. */\n`;
}

function primitiveLines(set: TokenSet, indent = "  ") {
  const lines: string[] = [];
  for (const r of set.ramps) for (const [step, hex] of Object.entries(r.steps)) lines.push(`${indent}${cssVar(`color/${r.name}/${step}`)}: ${cssColor(hex)};`);
  return lines;
}

function semanticLines(set: TokenSet, mode: Mode, indent = "  ") {
  return set.semantic.map((s) => `${indent}${cssVar(s.path)}: ${semanticValue(s[mode])};`);
}

/** Semantic mode blocks: light on :root, dark on [data-theme="dark"] and the OS preference. */
function modeBlocks(set: TokenSet, settings: SystemSettings) {
  const modes = modesOf(settings);
  if (modes.length === 1) return `:root {\n${semanticLines(set, modes[0]).join("\n")}\n}\n`;
  const dark = semanticLines(set, "dark", "    ").join("\n");
  return `:root,\n[data-theme="light"] {\n  color-scheme: light;\n${semanticLines(set, "light").join("\n")}\n}\n\n[data-theme="dark"] {\n  color-scheme: dark;\n${semanticLines(set, "dark").join("\n")}\n}\n\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n    color-scheme: dark;\n${dark}\n  }\n}\n`;
}

export function toTokensCss(set: TokenSet, meta: CssMeta): string {
  const lines: string[] = ["  /* Colour primitives */", ...primitiveLines(set)];
  if (set.fonts.length) {
    lines.push("", "  /* Fonts */");
    for (const f of set.fonts) lines.push(`  ${cssVar(`font/${f.key}`)}: ${fontStack(f.family, f.fallback)};`);
  }
  if (set.typeScale.length) {
    lines.push("", "  /* Type scale */");
    for (const t of set.typeScale) {
      const v = cssVar(`text/${t.name}`);
      lines.push(
        `  ${v}-font: var(${cssVar(`font/${t.font}`)});`,
        `  ${v}-size: ${t.size}px;`,
        `  ${v}-line-height: ${t.lineHeight}px;`,
        `  ${v}-weight: ${t.weight};`,
        `  ${v}-tracking: ${t.letterSpacing}em;`,
      );
    }
  }
  const dims = (title: string, prefix: string, items: { name: string; value: number }[]) => {
    if (!items.length) return;
    lines.push("", `  /* ${title} */`, ...items.map((d) => `  ${cssVar(`${prefix}/${d.name}`)}: ${d.value}px;`));
  };
  dims("Spacing", "space", set.spacing);
  dims("Radius", "radius", set.radius);
  if (set.shadows.length) {
    lines.push("", "  /* Shadows */", ...set.shadows.map((s) => `  ${cssVar(`shadow/${s.name}`)}: ${shadowCss(s)};`));
  }
  dims("Breakpoints (for reference; CSS can't use variables in media queries)", "breakpoint", set.breakpoints);

  return `${header(meta, "tokens.css")}\n:root {\n${lines.join("\n")}\n}\n\n/* Semantic colours */\n${modeBlocks(set, meta.settings)}`;
}

/** Tailwind v4: import after tailwindcss. Utilities like bg-bg-default, text-text-muted, p-4, rounded-md, shadow-md. */
export function toTailwindCss(set: TokenSet, meta: CssMeta): string {
  const modes = modesOf(meta.settings);
  const theme: string[] = ["  /* Colour primitives */", ...primitiveLines(set)];
  theme.push("", "  /* Semantic colours (switch with data-theme) */", ...semanticLines(set, modes[0]));
  if (set.fonts.length) {
    theme.push("", ...set.fonts.map((f) => `  ${cssVar(`font/${f.key}`)}: ${fontStack(f.family, f.fallback)};`));
  }
  if (set.typeScale.length) {
    theme.push("");
    for (const t of set.typeScale) {
      const v = cssVar(`text/${t.name}`);
      theme.push(
        `  ${v}: ${t.size}px;`,
        `  ${v}--line-height: ${t.lineHeight}px;`,
        `  ${v}--font-weight: ${t.weight};`,
        `  ${v}--letter-spacing: ${t.letterSpacing}em;`,
      );
    }
  }
  if (set.spacing.length) theme.push("", ...set.spacing.map((d) => `  ${cssVar(`spacing/${d.name}`)}: ${d.value}px;`));
  if (set.radius.length) theme.push("", ...set.radius.map((d) => `  ${cssVar(`radius/${d.name}`)}: ${d.value}px;`));
  if (set.shadows.length) theme.push("", ...set.shadows.map((s) => `  ${cssVar(`shadow/${s.name}`)}: ${shadowCss(s)};`));
  if (set.breakpoints.length) theme.push("", ...set.breakpoints.map((d) => `  ${cssVar(`breakpoint/${d.name}`)}: ${d.value}px;`));

  let out = `${header(meta, "tailwind.css")}/* Usage: @import "tailwindcss"; @import "./tailwind.css"; */\n\n`;
  if (modes.length > 1) out += `@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));\n\n`;
  out += `@theme {\n${theme.join("\n")}\n}\n`;
  if (modes.length > 1) {
    out += `\n[data-theme="dark"] {\n  color-scheme: dark;\n${semanticLines(set, "dark").join("\n")}\n}\n`;
  }
  return out;
}
