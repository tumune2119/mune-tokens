// Reading a hand-edited UI-CONFIG.md back in ("Keep my edits").

function sections(md: string) {
  const map = new Map<string, string[]>();
  let current = "";
  for (const line of md.split(/\r?\n/)) {
    const h = line.match(/^#{2,3}\s+(.*)$/);
    if (h) {
      current = h[1].trim().toLowerCase();
      map.set(current, []);
      continue;
    }
    map.get(current)?.push(line);
  }
  return map;
}

function rows(lines: string[]) {
  return lines
    .filter((l) => l.trim().startsWith("|") && !/^\|\s*-/.test(l.trim()))
    .slice(1) // header
    .map((l) =>
      l
        .trim()
        .replace(/^\||\|$/g, "")
        .split(/(?<!\\)\|/)
        .map((c) => c.trim().replace(/\\\|/g, "|")),
    );
}

const strip = (s: string) => s.replace(/`/g, "").trim();
const firstHex = (s: string) => s.match(/#[0-9a-f]{6}([0-9a-f]{2})?\b/i)?.[0]?.toLowerCase();
const firstRef = (s: string) => s.match(/color\/[a-z0-9-]+\/[a-z0-9-]+/i)?.[0]?.toLowerCase();
const num = (s: string) => {
  const n = Number.parseFloat(s.replace(/[^\d.-]/g, ""));
  return Number.isFinite(n) ? n : null;
};

/**
 * Applies the values in a UI-CONFIG.md to a token set. Only tables the app writes are read; tokens
 * that aren't in the file stay as they are, new rows are added. Shadows are read-only (kept from the app).
 */
export function applyUiConfig(base: TokenSet, md: string, settings: SystemSettings): { set: TokenSet; changes: number } {
  const set: TokenSet = structuredClone(base);
  const modes = modesOf(settings);
  const secs = sections(md);
  let changes = 0;

  const semantic = secs.get("colour — semantic");
  if (semantic) {
    for (const r of rows(semantic)) {
      const p = strip(r[0] ?? "").toLowerCase();
      if (!/^color\//.test(p)) continue;
      const values = modes.map((_, i) => {
        const c = r[1 + i] ?? "";
        return firstRef(c) ?? firstHex(c);
      });
      const on = strip(r[2 + modes.length] ?? "").toLowerCase().match(/^color(\/[a-z0-9-]+)+$/)?.[0] ?? null;
      const desc = r[3 + modes.length]?.trim() || null;
      let token = set.semantic.find((s) => s.path === p);
      if (!token) {
        token = { path: p, light: values[0] ?? "#000000", dark: values[values.length - 1] ?? "#000000", on: null, description: null };
        set.semantic.push(token);
        changes++;
      }
      modes.forEach((m, i) => {
        if (values[i] && values[i] !== token![m]) {
          token![m] = values[i]!;
          changes++;
        }
      });
      if (modes.length === 1) token[modes[0] === "light" ? "dark" : "light"] = token[modes[0]];
      if ((on ?? null) !== (token.on ?? null)) {
        token.on = on;
        changes++;
      }
      if (desc !== (token.description ?? null)) {
        token.description = desc;
        changes++;
      }
    }
  }

  for (const [title, lines] of secs) {
    if (!/\(base #/.test(title)) continue;
    const rampName = title.split(" ")[0];
    const ramp = set.ramps.find((r) => r.name === rampName);
    if (!ramp) continue;
    for (const r of rows(lines)) {
      const p = strip(r[0] ?? "");
      const step = p.split("/")[2];
      const hex = hexSchema.safeParse(strip(r[1] ?? ""));
      if (step && hex.success && ramp.steps[step] !== hex.data) {
        ramp.steps[step] = hex.data;
        changes++;
      }
    }
  }

  const fonts = secs.get("fonts");
  if (fonts) {
    for (const r of rows(fonts)) {
      const key = strip(r[0] ?? "").replace(/^font\//, "");
      const family = strip(r[1] ?? "");
      const fallback = strip(r[2] ?? "");
      if (!key || !family) continue;
      const f = set.fonts.find((x) => x.key === key);
      if (!f) {
        set.fonts.push({ key, family, fallback });
        changes++;
      } else if (f.family !== family || f.fallback !== fallback) {
        Object.assign(f, { family, fallback });
        changes++;
      }
    }
  }

  const scale = secs.get("type scale");
  if (scale) {
    for (const r of rows(scale)) {
      const name = strip(r[0] ?? "");
      if (!name) continue;
      const next = {
        name,
        font: strip(r[1] ?? "").replace(/^font\//, "") || "sans",
        size: num(r[2] ?? "") ?? 16,
        lineHeight: num(r[3] ?? "") ?? 24,
        weight: num(r[4] ?? "") ?? 400,
        letterSpacing: num(r[5] ?? "") ?? 0,
      };
      const t = set.typeScale.find((x) => x.name === name);
      if (!t) {
        set.typeScale.push(next);
        changes++;
      } else if (JSON.stringify({ ...t }) !== JSON.stringify({ ...t, ...next })) {
        Object.assign(t, next);
        changes++;
      }
    }
  }

  const dims = (title: string, key: "spacing" | "radius" | "breakpoints") => {
    const lines = secs.get(title);
    if (!lines) return;
    for (const r of rows(lines)) {
      const name = strip(r[0] ?? "").split("/").slice(1).join("-");
      const value = num(r[1] ?? "");
      if (!name || value === null) continue;
      const d = set[key].find((x) => x.name === name);
      if (!d) {
        set[key].push({ name, value });
        changes++;
      } else if (d.value !== value) {
        d.value = value;
        changes++;
      }
    }
  };
  dims("spacing", "spacing");
  dims("radius", "radius");
  dims("breakpoints", "breakpoints");

  return { set, changes };
}
