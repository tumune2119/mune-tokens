import { oklchLabel, resolveRef } from "../tokens/color";
import { cssVar, hexSchema, modesOf, type SystemSettings, type TokenSet } from "../tokens/schema";
import { fontStack, shadowCss } from "./css";
import type { ComponentSpec } from "../components/schema";

export interface UiConfigMeta {
  name: string;
  version: number;
  date: string;
  settings: SystemSettings;
  brief?: string;
  /** Ready components (written when the system includes do/don't rules). */
  components?: ComponentSpec[];
}

const code = (s: string) => `\`${s}\``;
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

function table(head: string[], rows: string[][]) {
  return [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");
}

/** UI-CONFIG.md: written for an AI reader — explicit, rule-based, every name matches Figma and CSS. */
export function toUiConfig(set: TokenSet, meta: UiConfigMeta): string {
  const modes = modesOf(meta.settings);
  const rules = meta.settings.uiConfig === "tokens+rules";
  const out: string[] = [];
  out.push(`# UI Config — ${meta.name}`);
  out.push(`Version ${meta.version} · ${meta.date} · generated by MUNE Tokens`);
  out.push(`Source of truth: tokens.json in this folder. Do not invent values outside this file.`);
  if (meta.brief?.trim()) out.push("", `> ${meta.brief.trim().replace(/\r?\n+/g, " ")}`);

  out.push("", "## Rules for the AI");
  out.push(
    "- Use only the tokens below. Never hard-code hex, px or font values.",
    "- Use semantic tokens in UI code; primitives only to define semantics.",
    modes.length > 1
      ? "- Modes: light + dark. Every colour use must work in both (switch with `data-theme=\"dark\"` on <html>)."
      : `- Mode: ${modes[0]} only.`,
    meta.settings.contrast === "AAA"
      ? "- Contrast target: WCAG AAA (7:1 text, 4.5:1 large text, 3:1 UI)."
      : "- Contrast target: WCAG AA (4.5:1 text, 3:1 large text and UI).",
    "- Stack hint: Tailwind v4 — import tailwind.css; or plain CSS — import tokens.css.",
    "- Token names map one-to-one: `color/bg/default` ↔ `--color-bg-default` ↔ Figma variable `color/bg/default`.",
  );

  if (set.semantic.length) {
    out.push("", "## Colour — semantic");
    const head = ["Token", ...modes.map((m) => (m === "light" ? "Light" : "Dark")), "CSS var", "On", "Use"];
    out.push(
      table(
        head,
        set.semantic.map((s) => [
          code(s.path),
          ...modes.map((m) => `${code(s[m])}${s[m].startsWith("#") ? "" : ` ${resolveRef(set, s[m]) ?? "?"}`}`),
          code(cssVar(s.path)),
          s.on ? code(s.on) : "",
          s.description ?? "",
        ]),
      ),
    );
  }

  if (set.ramps.length) {
    out.push("", "## Colour — primitives");
    for (const r of set.ramps) {
      out.push("", `### ${r.name} (base ${r.base})`);
      out.push(
        table(
          ["Token", "Hex", "OKLCH", "CSS var"],
          Object.entries(r.steps).map(([step, hex]) => [code(`color/${r.name}/${step}`), hex, oklchLabel(hex), code(cssVar(`color/${r.name}/${step}`))]),
        ),
      );
    }
  }

  if (set.fonts.length || set.typeScale.length) {
    out.push("", "## Typography");
    if (set.fonts.length) {
      out.push("", "### Fonts");
      out.push(table(["Font token", "Family", "Fallback", "CSS var"], set.fonts.map((f) => [code(`font/${f.key}`), f.family, f.fallback, code(cssVar(`font/${f.key}`))])));
      out.push("", `CSS: ${set.fonts.map((f) => code(fontStack(f.family, f.fallback))).join(" · ")}`);
    }
    if (set.typeScale.length) {
      out.push("", "### Type scale");
      out.push(
        table(
          ["Style", "Font", "Size", "Line height", "Weight", "Tracking", "CSS vars"],
          set.typeScale.map((t) => [
            code(t.name),
            code(`font/${t.font}`),
            `${t.size}px`,
            `${t.lineHeight}px`,
            String(t.weight),
            `${t.letterSpacing}em`,
            code(`${cssVar(`text/${t.name}`)}-*`),
          ]),
        ),
      );
    }
  }

  const dims = (title: string, prefix: string, items: { name: string; value: number }[]) => {
    if (!items.length) return;
    out.push("", `## ${title}`);
    out.push(table(["Token", "Value", "CSS var"], items.map((d) => [code(`${prefix}/${d.name}`), `${d.value}px`, code(cssVar(`${prefix}/${d.name}`))])));
  };
  dims("Spacing", "space", set.spacing);
  dims("Radius", "radius", set.radius);
  if (set.shadows.length) {
    out.push("", "## Shadows");
    out.push(table(["Token", "CSS", "CSS var"], set.shadows.map((s) => [code(`shadow/${s.name}`), code(shadowCss(s)), code(cssVar(`shadow/${s.name}`))])));
  }
  dims("Breakpoints", "breakpoint", set.breakpoints);

  if (rules && meta.components?.length) {
    out.push("", "## Components", "Build these exactly: same names, parts, variants, states and token bindings as the Figma components.");
    for (const c of meta.components) {
      out.push("", `### ${c.name} (${c.level})`);
      if (c.description) out.push(c.description);
      const tree = (parent: string | null, depth: number): string[] =>
        c.anatomy
          .filter((p) => (p.parent ?? null) === parent)
          .flatMap((p) => [
            `${"  ".repeat(depth)}- \`${p.name}\` ${p.kind}${p.direction && p.kind === "container" ? ` (${p.direction})` : ""}${p.icon ? ` icon:${p.icon}` : ""}${p.text ? ` "${p.text}"` : ""}`,
            ...tree(p.name, depth + 1),
          ]);
      out.push("", "Anatomy:", ...tree(null, 0));
      if (c.props.length) out.push("", `Variants: ${c.props.map((p) => `\`${p.name}\` = ${p.values.join(" | ")}`).join("; ")}`);
      out.push(`States: ${c.states.join(", ")}`);
      out.push("", "Token bindings:");
      for (const r of c.styles) {
        const when = Object.entries(r.when ?? {}).map(([k, v]) => `${k}=${v}`).join(", ");
        const set = Object.entries(r.set)
          .filter(([, v]) => v !== undefined)
          .map(([k, v]) => `${k} → ${typeof v === "number" ? (k === "opacity" ? v : `${v}px`) : `\`${v}\``}`)
          .join(", ");
        out.push(`- \`${r.part}\`${when ? ` [${when}]` : ""}: ${set}`);
      }
      const a = c.a11y;
      const a11y = [a.role && `role ${a.role}`, a.keyboard, a.minTarget ? `min target ${a.minTarget}px` : "", ...a.notes].filter(Boolean);
      if (a11y.length) out.push("", `Accessibility: ${a11y.join("; ")}`);
      if (c.content.length) out.push(`Content: ${c.content.join("; ")}`);
    }
  }

  if (rules) {
    out.push("", "## Do / Don't");
    out.push(
      "- Do use `color/text/*` on `color/bg/*` pairs listed above; check the `On` column for the intended background.",
      "- Do use the spacing scale for padding, gaps and margins; don't use values between steps.",
      "- Do use the type scale styles as a set (size + line height + weight + tracking together).",
      "- Don't use colour as the only signal for state; pair it with an icon or text.",
      "- Don't reference primitives (`color/<ramp>/<step>`) directly in components.",
    );
  }

  out.push("", "## Figma");
  out.push(
    `File: ${meta.settings.figmaUrl || "(not set)"} · Variables collections: Primitives, Semantic · Modes: ${modes.map((m) => (m === "light" ? "Light" : "Dark")).join(", ")}`,
  );
  return out.join("\n") + "\n";
}

