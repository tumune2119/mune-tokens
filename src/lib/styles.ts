/** Prompt block with the AI-tell rules (empty when switched off). */
export function distinctiveGuidance(on: boolean | undefined, scope: "tokens" | "all"): string {
  if (on === false) return "";
  const rules = scope === "tokens" ? AI_TELLS.tokens : [...AI_TELLS.tokens, ...AI_TELLS.product];
  return `\n\nAvoid the generic AI look (a visual style chosen above wins where they overlap):\n${rules.map((r) => `- ${r}`).join("\n")}`;
}

/** Everything about visual direction for a prompt: picked styles, then the AI-tell rules. */
export function directionBlock(settings: { style?: string[]; distinctive?: boolean }, scope: "tokens" | "all") {
  return styleGuidance(settings.style) + distinctiveGuidance(settings.distinctive, scope);
}
