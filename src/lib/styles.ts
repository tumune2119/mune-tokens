/** Prompt block for the picked styles (empty when none). */
export function styleGuidance(ids: string[] | undefined): string {
  const picked = (ids ?? []).map(styleById).filter((s): s is VisualStyle => !!s);
  if (!picked.length) return "";
  const blend =
    picked.length > 1
      ? `\nBlend these styles: use ${picked[0].name} as the base and ${picked[1].name} as the accent layer (where they conflict, ${picked[0].name} wins).`
      : "";
  return `\n\nVisual style (follow closely; it overrides generic defaults, but contrast targets and the output rules still apply):${blend}
${picked
  .map(
    (s) => `\n## ${s.name}: ${s.blurb}
- Colour: ${s.colour}
- Type: ${s.type}
- Shape/radius: ${s.shape}
- Depth/shadows: ${s.depth}
- Spacing: ${s.space}
- Motion: ${s.motion}
- Components: ${s.components}
- Avoid: ${s.avoid}`,
  )
  .join("\n")}`;
}

